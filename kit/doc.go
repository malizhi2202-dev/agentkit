// Package kit 是 agentkit 的**装配根**：把散在各包的注入点收成一个统一、可插拔、可撤销的生命周期。
//
// 权威依据：`ADR-011`（插件契约与两阶段注册）、`ADR-012`（出口基线按符号方向判定）、
// `ADR-002`（引擎无状态 ⇒ 本包**不持有任何会话/记忆**，只编排调用方携带的上下文）、
// `L-014`/R3（同一不变量不写两遍）、`L-096`（多条独立判据必须全量收集后统一报红）。
//
// 三条设计取舍，先写在这里，免得读者以为"还能更聪明"：
//
//  1. **零反射、零字符串服务定位器**。`Kit` 的服务是**具名字段/具名方法**（现在是 `Tools`，
//     后续批次再加 `Perms`/`Audit`/`Web`…），编译期可查，不出现 `k.Get("tools")` 这种
//     把拼写错误推到运行期的写法。
//  2. **不预先造无人使用的抽象**（P7c 已按此判据评估并否决 `Registry[T]`：三个使用者的锁/派生键/
//     Trim/拷贝四个轴互不相同，抽出来只是在记录差异 —— 理由逐条写在 `authz/doc.go`）。
//     注册表泛型基座（`Registry[T]`）当年推迟到它第一个真实使用者
//     （P2 `authz`）出现时再写；本包只交付今天就要用的东西：契约 + 两阶段 + 依赖排序 + 可撤销。
//  3. **复用既有唯一实现，不复制校验**。工具声明直接进既有的 `tools.Registry`：
//     空名/重名/`Run==nil`（半成品声明）/角色裁剪谓词全部沿用其单一实现（ADR-010 允许框架内部 import）。
//
// 生命周期（`New` → `Use`* → `Build` → 运行 → `Stop`）的任何一步失败都**不留半初始化对象**：
// `Build` 失败时已 `Apply` 的插件按逆序被撤销，`Kit` 转入 `stopped` 状态且不再可用。
