// Package authz 是权限点的**声明与值域**层：一张注册表 + 三个闭集，不含任何授权判定。
//
// 取材：日志微服务 `client/internal/auth/permissions.go` 的注册表形状（有序切片 + 一次建索引 +
// "代码即文档"的字段），值域沿用 宿主侧 既有口径 —— 角色词汇表来自 `既有实现目录 ` 的
// `LocalPermision*` 常量族，引擎侧 `既有管理面/permission.go:252` 已经把"本层一个角色
// 字面量都不写"用 AST 断言钉住，本包**照抄这条纪律**（见 TestAuthz_NoRoleLiteralInSource）。
//
// 三条不可让的规矩：
//
//  1. **本包不判定授权**。框架内授权谓词只有一条：`tools.Registry` 的 `Tool.allows`
//     （`TrimByRole`/`VisibleByRole`/`LookupAuthorized` 共用它）。本包只把"权限点 ⇒ 角色集合"
//     解析出来，用于**生成** `tools.Tool.RequiredRoles`；再造一个 `Allowed(...)` 就是把同一
//     不变量写两遍（REVIEW-2 节C-1 实测踩过：角色枚举三份、只有一份有守卫）。
//  2. **闭集外一律判失败，不静默剔除**。角色的**具体取值由宿主注入**（`NewRoleSet`）：框架要可
//     插拔，就不能把某个部署的角色表写死在代码里；但"必须落在注入的闭集内"是框架的规矩。
//     注册时越界 ⇒ 直接失败并点名（对照引擎链路里"闭集外角色被剔除"的口径：那里是运行时上游
//     数据，可以剔除并留痕；这里是开发者写的声明，写错就该在装配期炸，不该悄悄改掉）。
//  3. **空默认角色一律拒绝注册**。因为 `allows` 把"空 `RequiredRoles`"解释为
//     "任意已判定角色可用"，所以"权限点存在但谁都不给"如果允许声明，一旦有人把键名写错，
//     生成出来的工具就变成公开工具 —— 这是 fail-open。要表达"这个接口公开"，正确做法是
//     **不挂权限点**，而不是挂一个空角色权限点。
//
// 已评估并放弃的抽象（P7c，2026-10-15）：曾登记"等第三个同类注册表（`scene`）落地时一次性抽
// `Registry[T]`"。三个使用者齐了，逐字段比对后判定**不抽**，理由是四个轴上三者本就不同：
//   - 并发：本表**刻意无锁**（Build 期封存、之后只读）；`tools`/`scene` 各带 `sync.RWMutex`。
//     共用基座等于给安全件的热路径加锁，并改掉它已写明的并发契约。
//   - 存的東西：本表存**条目**（`points []PermissionPoint`）并从条目派生键，因为 `All` 每次都要
//     交出深拷贝的 `DefaultRoles`；`tools`/`scene` 存**键序 + 值索引**两份。
//   - 读键归一化：本表 `Lookup` **做** TrimSpace，`tools.Registry.Lookup` **不做**。
//   - 空接收者：三者的 nil 语义相同但落点不同（有锁的必须先判 nil 再 RLock）。
//
// 要合并就得给基座加四个开关（锁/派生键/Trim/拷贝），每多一个开关都表示基座只是在**记录差异**而不是
// 消除差异 —— 而代价是改动两个承载安全不变量的文件。故此处保留这份重复骨架，并把它写清为何保留。
